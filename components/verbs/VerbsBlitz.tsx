"use client";

import { useEffect, useRef, useState } from "react";
import { ArrowLeft, RotateCcw, Zap } from "lucide-react";
import type { DictionaryEntry } from "@/lib/db/dictionaryStore";
import { diffExpected } from "@/lib/srs/activeTraining";
import { CONJUGATION_TENSE_LABEL, CONJUGATION_TENSE_ORDER, type ConjugationTense } from "@/lib/verbsQuizModes";
import { DictateButton, type DictateButtonHandle } from "@/components/discover/DictateButton";
import { checkAgainstAlternatives } from "@/lib/verbConjugation";
import { isPresentPluralInfinitive } from "@/lib/verbForms";
import { BLITZ_SECONDS, buildBlitzCells, shuffleBlitzDeck, type BlitzCell } from "@/lib/verbBlitz";
import { conjugationOnDevice, verbLemma } from "@/components/verbs/VerbsQuiz";

type Props = {
  verbs: DictionaryEntry[];
  targetLanguage: string;
  tenses: Set<ConjugationTense>;
  onExit: () => void;
};

type BlitzAnswer = { cell: BlitzCell; given: string; correct: boolean; expected: string };

const PRONOUNS = new Set(["ich", "du", "er", "sie", "es", "wir", "ihr"]);

/**
 * Speech hands back «du fährst», and some people type the pronoun out of
 * habit — the card already shows it, so a leading pronoun is dropped unless
 * the form itself starts with one (reflexive «mich», not a pronoun here).
 */
function withoutPronoun(given: string, expected: string): string {
  const words = given.trim().split(/\s+/);
  const first = words[0]?.toLocaleLowerCase("de-DE");
  if (words.length < 2 || !first || !PRONOUNS.has(first)) return given.trim();
  if (expected.toLocaleLowerCase("de-DE").split(/\s+/)[0] === first) return given.trim();
  return words.slice(1).join(" ");
}

function buildCells(verbs: DictionaryEntry[], tenses: Set<ConjugationTense>, targetLanguage: string): BlitzCell[] {
  const byId = new Map(verbs.map((entry) => [entry.id, entry]));
  const ordered = CONJUGATION_TENSE_ORDER.filter((tense) => tenses.has(tense));
  return buildBlitzCells(
    verbs.map((entry) => ({ id: entry.id, verb: entry.headword, translation: entry.translation ?? undefined })),
    ordered.length ? ordered : ["present"],
    (id, tense) => conjugationOnDevice(byId.get(id)!, tense, targetLanguage),
    (id, tense, row) => {
      if (tense !== "present") return false;
      const entry = byId.get(id)!;
      return isPresentPluralInfinitive(row.label, row.form, verbLemma(entry), entry.forms?.trennbar);
    },
  );
}

/**
 * «Блиц»: a minute of single cells — one person, one verb, one tense — mixed
 * across the pack, typed or spoken as fast as possible. Built only from the
 * tables already on the device (generated by rule or saved from an earlier
 * AI answer): no AI call, ever. A warm-up — the answers do not touch the
 * drill schedule.
 */
export function VerbsBlitz({ verbs, targetLanguage, tenses, onExit }: Props) {
  const [cells] = useState(() => buildCells(verbs, tenses, targetLanguage));
  const [deck, setDeck] = useState<BlitzCell[]>(() => shuffleBlitzDeck(cells));
  const [index, setIndex] = useState(0);
  const [phase, setPhase] = useState<"ready" | "running" | "done">("ready");
  const [deadline, setDeadline] = useState(0);
  const [now, setNow] = useState(0);
  const [input, setInput] = useState("");
  const [answers, setAnswers] = useState<BlitzAnswer[]>([]);
  const inputRef = useRef<HTMLInputElement>(null);
  const startRef = useRef<HTMLButtonElement>(null);
  const dictateRef = useRef<DictateButtonHandle>(null);

  const cell = deck[index % Math.max(deck.length, 1)];
  const secondsLeft = Math.max(0, Math.ceil((deadline - now) / 1000));
  const last = answers.at(-1);
  const verbCount = new Set(cells.map((c) => c.entryId)).size;

  useEffect(() => {
    if (phase !== "running") return;
    const timer = window.setInterval(() => {
      const t = Date.now();
      setNow(t);
      if (t >= deadline) setPhase("done");
    }, 200);
    return () => window.clearInterval(timer);
  }, [phase, deadline]);

  useEffect(() => {
    if (phase === "running") inputRef.current?.focus();
    if (phase === "ready") startRef.current?.focus();
  }, [phase]);

  function start() {
    if (cells.length === 0) return;
    const t = Date.now();
    setDeck(shuffleBlitzDeck(cells));
    setIndex(0);
    setAnswers([]);
    setInput("");
    setNow(t);
    setDeadline(t + BLITZ_SECONDS * 1000);
    setPhase("running");
  }

  function submit(raw: string) {
    if (phase !== "running" || !cell || Date.now() >= deadline) return;
    const given = withoutPronoun(raw, cell.expected);
    const check = checkAgainstAlternatives(given, cell.expected, "exact");
    setAnswers((prev) => [...prev, { cell, given, correct: check.verdict === "correct", expected: check.matched }]);
    setInput("");
    // The whole deck went by inside the minute — a fresh shuffle, not the same order again.
    if (index + 1 >= deck.length) {
      setDeck(shuffleBlitzDeck(cells));
      setIndex(0);
    } else {
      setIndex(index + 1);
    }
  }

  // DictateButton keeps the onText it was given when listening started, so
  // speech goes through a ref that always points at the current card.
  const submitRef = useRef(submit);
  submitRef.current = submit;

  const header = (title: string) => (
    <header className="screen-header">
      <button className="icon-btn" onClick={onExit} type="button" aria-label="Назад">
        <ArrowLeft size={20} />
      </button>
      <div>
        <p className="eyebrow">Глаголы · блиц</p>
        <h1>{title}</h1>
      </div>
    </header>
  );

  if (cells.length === 0) {
    return (
      <section className="screen verbs-view verb-quiz">
        {header("Нечего спрягать")}
        <div className="verb-quiz-summary">
          <p>Для этих глаголов на устройстве ещё нет таблиц спряжения. Пройдите их один раз в «Тренировать» с режимом «Спряжения» — потом блиц возьмёт формы оттуда.</p>
          <button type="button" className="secondary-btn" onClick={onExit}>Назад</button>
        </div>
      </section>
    );
  }

  if (phase === "ready") {
    return (
      <section className="screen verbs-view verb-quiz">
        {header(`${BLITZ_SECONDS} секунд`)}
        <div className="verb-quiz-summary">
          <p>Лицо + глагол + время — пишите форму и Enter, или скажите её голосом. {cells.length} ячеек из {verbCount} {verbCount === 1 ? "глагола" : "глаголов"}. В расписание не идёт — это разминка.</p>
          <button type="button" ref={startRef} className="primary-btn" onClick={start}>
            <Zap size={16} style={{ marginRight: 6 }} /> Старт
          </button>
        </div>
      </section>
    );
  }

  if (phase === "done") {
    const mistakes = answers.filter((answer) => !answer.correct);
    const correct = answers.length - mistakes.length;
    return (
      <section className="screen verbs-view verb-quiz">
        {header("Время!")}
        <div className="verb-quiz-summary">
          <strong className="verb-blitz-score">{correct}</strong>
          <p>верно из {answers.length}{mistakes.length ? ` · ошибок ${mistakes.length}` : answers.length ? " · без ошибок" : ""}</p>
          {mistakes.length > 0 && (
            <ul className="verb-blitz-mistakes">
              {mistakes.map((m, i) => (
                <li key={i}>
                  <span className="verb-blitz-mistake-cell">{m.cell.person} · {m.cell.verb} · {CONJUGATION_TENSE_LABEL[m.cell.tense]}</span>
                  <span className="verb-blitz-mistake-forms">
                    <s>{m.given || "—"}</s>{" → "}
                    {diffExpected(m.given, m.expected).map((seg, si) => (
                      <span key={si} className={seg.changed ? "verb-quiz-diff" : undefined}>{seg.text}</span>
                    ))}
                  </span>
                </li>
              ))}
            </ul>
          )}
          <button type="button" className="primary-btn" onClick={start}>
            <RotateCcw size={16} style={{ marginRight: 6 }} /> Ещё раз
          </button>
          <button type="button" className="secondary-btn" onClick={onExit}>К глаголам</button>
        </div>
      </section>
    );
  }

  const correctSoFar = answers.filter((answer) => answer.correct).length;
  return (
    <section className="screen verbs-view verb-quiz">
      <header className="screen-header">
        <button className="icon-btn" onClick={onExit} type="button" aria-label="Назад">
          <ArrowLeft size={20} />
        </button>
        <div>
          <p className="eyebrow">Глаголы · блиц · {correctSoFar} верно</p>
          <h1 className={`verb-blitz-timer${secondsLeft <= 10 ? " low" : ""}`}>0:{String(secondsLeft).padStart(2, "0")}</h1>
        </div>
      </header>
      <div className="verb-blitz-bar"><span style={{ width: `${(secondsLeft / BLITZ_SECONDS) * 100}%` }} /></div>

      <div className="verb-quiz-card">
        <p className="verb-blitz-tense">{CONJUGATION_TENSE_LABEL[cell.tense]}</p>
        <div className="verb-quiz-infinitive">
          <span className="verb-blitz-person">{cell.person}</span>
          <span>{cell.verb}</span>
        </div>
        {cell.translation && <p className="verb-quiz-translation">{cell.translation}</p>}
        <div className="verb-quiz-input-row">
          <input
            ref={inputRef}
            type="text"
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={(e) => {
              if (e.ctrlKey && e.code === "Space") {
                e.preventDefault();
                dictateRef.current?.toggle();
                return;
              }
              if (e.key !== "Enter") return;
              e.preventDefault();
              submit(input);
            }}
            aria-label={`${cell.person} ${cell.verb}, ${CONJUGATION_TENSE_LABEL[cell.tense]}`}
            autoComplete="off"
            autoCorrect="off"
            autoCapitalize="off"
            spellCheck={false}
            enterKeyHint="next"
            className="verb-quiz-input"
          />
          <DictateButton
            ref={dictateRef}
            lang={targetLanguage}
            title="Сказать голосом (или Ctrl+Space в поле)"
            onText={(text) => submitRef.current(text)}
          />
        </div>
        {last && (
          <p className={`verb-blitz-last ${last.correct ? "correct" : "wrong"}`}>
            {last.correct ? "✓" : "✗"} {last.cell.person} {last.correct ? last.given : last.expected}
            {!last.correct && last.given && <s> {last.given}</s>}
          </p>
        )}
      </div>
    </section>
  );
}
